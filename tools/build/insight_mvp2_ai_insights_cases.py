                head = [f'บัญชีที่ใช้ (UAT): {email} · บทบาท "{role}"', f'workspace: "{ws}" · ช่วงเวลา: "{period}"']
                c['data'] = head + extra + [d for d in (c.get('data') or []) if 'บัญชีที่ใช้' not in d]


